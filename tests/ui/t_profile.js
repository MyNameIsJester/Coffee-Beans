const H = require('./harness');
(async () => {
    await H.start();
    console.log('\n[profile.html]');
    let pg = await H.visit('register.html');
    pg.w.CB.auth.login('guest1', 'guest1123');
    let st = pg.snap();
    pg = await H.visit('profile.html', st);
    H.eq(pg.errors, [], 'không lỗi JS');
    const $ = (id) => pg.d.getElementById(id);
    H.eq($('displayName').textContent, 'Khách hàng 1', 'hiển thị họ tên tài khoản');
    H.ok(/Nguyễn Huệ/.test($('displayAddress').textContent), 'hiển thị địa chỉ tài khoản');
    H.eq($('editSection').classList.contains('show'), false, 'form sửa ẩn mặc định');
    $('editProfileBtn').click();
    H.ok($('editSection').classList.contains('show'), 'bấm Chỉnh sửa: hiện form');
    H.eq(pg.d.querySelector('#editForm [name=phone]').value, '0901000001', 'form hiện đúng dữ liệu hiện tại');
    const f = pg.d.getElementById('editForm');
    const submit = () => f.dispatchEvent(new pg.w.Event('submit', { cancelable: true }));
    f.elements.email.value = 'sai-email'; f.elements.phone.value = '12';
    submit();
    H.ok(/Email không hợp lệ/.test(f.querySelector('[data-error-for=email]').textContent) && /Số điện thoại không hợp lệ/.test(f.querySelector('[data-error-for=phone]').textContent), 'email/SĐT sai: báo lỗi');
    H.eq(pg.w.CB.auth.current().email, 'guest1@example.com', 'dữ liệu sai không được lưu');
    f.elements.email.value = 'guest2@example.com'; f.elements.phone.value = '0901000001';
    submit();
    H.ok(/đã được tài khoản khác sử dụng/.test(f.querySelector('[data-error-for=email]').textContent), 'trùng email tài khoản khác: báo lỗi');
    f.elements.email.value = 'moi@example.com'; f.elements.ward.value = '';
    submit();
    H.ok(/điền đủ địa chỉ/.test(f.querySelector('[data-error-for=ward]').textContent), 'địa chỉ thiếu 1 ô: báo lỗi');
    f.elements.ward.value = 'Phường Đa Kao'; f.elements.fullName.value = 'Tên Mới'; f.elements.district.value = 'Quận 3';
    submit();
    const u = pg.w.CB.auth.current();
    H.eq([u.fullName, u.email, u.address.ward, u.address.district], ['Tên Mới', 'moi@example.com', 'Phường Đa Kao', 'Quận 3'], 'lưu thành công');
    H.eq($('displayName').textContent, 'Tên Mới', 'giao diện cập nhật ngay');
    H.eq(pg.d.getElementById('accountText').textContent, 'Chào Tên Mới', 'header cập nhật tên');
    // tải lại: dữ liệu còn
    pg = await H.visit('profile.html', pg.snap());
    H.eq(pg.d.getElementById('displayEmail').textContent, 'moi@example.com', 'tải lại trang vẫn còn dữ liệu đã sửa');
    // xóa địa chỉ (để trống cả 4)
    pg.d.getElementById('editProfileBtn').click();
    const g = pg.d.getElementById('editForm');
    ['province', 'district', 'ward', 'detail'].forEach(k => g.elements[k].value = '');
    g.dispatchEvent(new pg.w.Event('submit', { cancelable: true }));
    H.eq(pg.w.CB.auth.hasAddress(pg.w.CB.auth.current()), false, 'để trống cả 4 ô: xóa địa chỉ');
    H.ok(/Chưa cập nhật/.test(pg.d.getElementById('displayAddress').textContent), 'hiển thị "Chưa cập nhật"');
    // đổi mật khẩu
    pg = await H.visit('profile.html', pg.snap());
    const $$ = (id) => pg.d.getElementById(id);
    H.eq($$('pwSection').classList.contains('show'), false, 'form đổi mật khẩu ẩn mặc định');
    $$('changePwBtn').click();
    H.ok($$('pwSection').classList.contains('show'), 'bấm Đổi mật khẩu: hiện form');
    H.eq([...pg.d.querySelectorAll('#pwForm input')].map(i => i.type), ['password', 'password', 'password'], 'cả 3 ô đều là type=password');
    H.ok(/localStorage/.test($$('pwSection').textContent) && /không phải/.test($$('pwSection').textContent), 'có ghi chú đây là chức năng minh họa dùng localStorage');
    const pw = pg.d.getElementById('pwForm');
    const sub = () => pw.dispatchEvent(new pg.w.Event('submit', { cancelable: true }));
    const errs = () => [...pw.querySelectorAll('[data-error-for]')].map(e => e.textContent);
    sub();
    H.ok(/Vui lòng nhập mật khẩu hiện tại/.test(errs()[0]) && /ít nhất 6/.test(errs()[1]), 'để trống: báo lỗi từng trường');
    pw.elements.currentPassword.value = 'sai'; pw.elements.newPassword.value = 'abcdef'; pw.elements.confirmPassword.value = 'abcdef'; sub();
    H.ok(/không đúng/.test(errs()[0]), 'mật khẩu hiện tại sai: báo lỗi');
    pw.elements.currentPassword.value = 'guest1123'; pw.elements.newPassword.value = 'abcdef'; pw.elements.confirmPassword.value = 'abcdeg'; sub();
    H.ok(/không khớp/.test(errs()[2]) && errs()[0] === '', 'xác nhận không khớp: báo lỗi đúng trường');
    pw.elements.confirmPassword.value = 'abcdef'; sub();
    H.ok(/Đã đổi mật khẩu thành công/.test(pg.d.querySelector('.cb-alert-info').textContent), 'đổi thành công: hiện thông báo');
    H.eq(pg.d.querySelector('#pwForm input').value, '', 'sau khi đổi: ô mật khẩu được xóa sạch');
    pg.w.CB.auth.logout();
    H.ok(!pg.w.CB.auth.login('guest1', 'guest1123').ok && pg.w.CB.auth.login('guest1', 'abcdef').ok, 'đăng nhập lại: mật khẩu cũ bị từ chối, mật khẩu mới được chấp nhận');
    // đăng xuất
    pg.w.confirm = () => true;
    pg.d.getElementById('logoutBtn').click();
    H.eq(pg.w.CB.auth.current(), null, 'đăng xuất xóa phiên');
    H.stop();
    process.exit(H.summary() ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
