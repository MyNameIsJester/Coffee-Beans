import sys; sys.path.insert(0, '/tmp/e2e')
from common import *
with sync_playwright() as p:
    b = p.chromium.launch(); ctx, logs = setup_context(b); pg = ctx.new_page(); watch(pg, logs); pg.set_default_timeout(8000)
    pg.on('dialog', lambda d: d.accept())
    pg.goto(BASE + 'register.html'); pg.fill('#login-identifier', 'guest1'); pg.fill('#login-password', 'guest1123'); pg.click('#loginForm button[type=submit]'); pg.wait_for_url('**/index.html')
    pg.goto(BASE + 'profile.html'); pg.wait_for_selector('#changePwBtn')
    check(not pg.locator('#pwSection').is_visible(), 'form đổi mật khẩu ẩn mặc định')
    pg.click('#changePwBtn'); pg.wait_for_selector('#pwSection', state='visible')
    pg.screenshot(path=SHOTS + 'pw_desktop.png', full_page=True)
    check(pg.locator('#pwForm input[type=password]').count() == 3, '3 ô mật khẩu đều ẩn ký tự')
    pg.click('#pwForm button[type=submit]'); check('hiện tại' in pg.inner_text('#pwForm'), 'để trống: báo lỗi')
    pg.fill('#currentPassword', 'sai'); pg.fill('#newPassword', 'matkhau9'); pg.fill('#confirmPassword', 'matkhau9'); pg.click('#pwForm button[type=submit]')
    check('không đúng' in pg.inner_text('#pwForm'), 'mật khẩu hiện tại sai: báo lỗi')
    pg.fill('#currentPassword', 'guest1123'); pg.fill('#newPassword', '123'); pg.click('#pwForm button[type=submit]'); check('ít nhất 6' in pg.inner_text('#pwForm'), 'mật khẩu mới quá ngắn: báo lỗi')
    pg.fill('#newPassword', 'matkhau9'); pg.fill('#confirmPassword', 'matkhau8'); pg.click('#pwForm button[type=submit]'); check('không khớp' in pg.inner_text('#pwForm'), 'xác nhận không khớp: báo lỗi')
    pg.fill('#confirmPassword', 'matkhau9'); pg.click('#pwForm button[type=submit]'); pg.wait_for_selector('.cb-alert-info')
    check('Đã đổi mật khẩu thành công' in pg.inner_text('.cb-alert-info'), 'đổi thành công: hiện thông báo')
    pg.reload(); pg.wait_for_selector('#displayName')
    check(pg.evaluate("CB.auth.current() !== null"), 'tải lại trang: vẫn đăng nhập')
    pg.evaluate("CB.auth.logout()")
    pg.goto(BASE + 'register.html'); pg.fill('#login-identifier', 'guest1'); pg.fill('#login-password', 'guest1123'); pg.click('#loginForm button[type=submit]')
    check('không đúng' in pg.inner_text('#loginForm .cb-alert'), 'mật khẩu cũ bị từ chối khi đăng nhập')
    pg.fill('#login-password', 'matkhau9'); pg.click('#loginForm button[type=submit]'); pg.wait_for_url('**/index.html')
    check(True, 'đăng nhập bằng mật khẩu mới thành công')
    check(pg.evaluate("CB.db.read(CB.db.KEYS.users,[]).every(u => JSON.stringify(u).indexOf('matkhau9') === -1)"), 'mật khẩu mới không lưu dạng văn bản thường trong localStorage')
    check(pg.evaluate("localStorage.getItem('cb_users').indexOf('guest2123') === -1"), 'không có mật khẩu nào lưu dạng văn bản thường')
    # mobile
    ctx2, logs2 = setup_context(b, 390, 844, True); m = ctx2.new_page(); watch(m, logs2)
    m.goto(BASE + 'register.html'); m.fill('#login-identifier', 'guest2'); m.fill('#login-password', 'guest2123'); m.click('#loginForm button[type=submit]'); m.wait_for_url('**/index.html')
    m.goto(BASE + 'profile.html'); m.click('#changePwBtn'); m.wait_for_selector('#pwSection', state='visible'); m.wait_for_timeout(800)
    m.screenshot(path=SHOTS + 'pw_mobile.png', full_page=True)
    m.evaluate("window.scrollTo(80,0)"); check(m.evaluate("window.scrollX") == 0, 'mobile: trang đổi mật khẩu không cuộn ngang')
    check(logs == [] and logs2 == [], 'không lỗi console', logs + logs2)
    b.close()
sys.exit(1 if summary() else 0)
