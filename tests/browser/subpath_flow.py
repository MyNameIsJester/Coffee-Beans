import sys; sys.path.insert(0, '/tmp/e2e')
import common
common.BASE = 'http://127.0.0.1:8766/CoffeeBeans/'
from common import *
with sync_playwright() as p:
    b = p.chromium.launch(); ctx, logs = setup_context(b); pg = ctx.new_page(); watch(pg, logs); pg.set_default_timeout(8000)
    bad = []
    pg.on('response', lambda r: bad.append((r.status, r.url)) if r.status >= 400 and r.url.startswith(common.BASE) else None)
    print('\n[Chạy dưới đường dẫn con /CoffeeBeans/ như GitHub Pages dạng project]')
    pg.goto('http://127.0.0.1:8766/CoffeeBeans/'); pg.wait_for_load_state('networkidle')
    check(pg.locator('#featuredGrid .card').count() == 3, 'mở thư mục gốc /CoffeeBeans/: hiện trang chủ (index.html)')
    check(pg.evaluate("[...document.images].filter(i=>i.complete&&i.naturalWidth===0).length") == 0, 'mọi ảnh tải được')
    check(pg.locator('a[href="#ve-chung-toi"]').count() >= 1, 'ở trang chủ: liên kết Giới thiệu là neo trong trang')
    check('dark-roast' in pg.evaluate("getComputedStyle(document.querySelector('.hero-media')).backgroundImage"), 'ảnh nền khai báo trong CSS (url(../images/...)) nạp được dưới đường dẫn con')
    pg.click('.account-link'); pg.wait_for_url('**/CoffeeBeans/register.html*')
    check('redirect=' in pg.url, 'chuyển tới trang đăng nhập đúng đường dẫn con', pg.url)
    pg.fill('#login-identifier', 'guest1'); pg.fill('#login-password', 'guest1123'); pg.click('#loginForm button[type=submit]'); pg.wait_for_url('**/CoffeeBeans/index.html')
    check(True, 'đăng nhập xong quay lại trang chủ index.html')
    pg.wait_for_selector('#accountText'); check('Chào Khách hàng 1' in pg.inner_text('#accountText'), 'header hiện tên tài khoản')
    pg.click('.dropdown > a'); pg.wait_for_url('**/CoffeeBeans/products.html'); pg.wait_for_selector('#productGrid .card')
    check(pg.locator('#productGrid .card').count() == 9, 'trang sản phẩm hoạt động')
    pg.locator('#productGrid button.add').first.click(); pg.wait_for_selector('.cb-toast')
    pg.click('a.badge'); pg.wait_for_url('**/CoffeeBeans/cart.html'); pg.wait_for_selector('.cart-table')
    pg.click('a[href="checkout.html"]'); pg.wait_for_url('**/CoffeeBeans/checkout.html'); pg.wait_for_selector('#placeOrder')
    pg.click('#placeOrder'); pg.wait_for_url('**/CoffeeBeans/order-confirmation.html*'); pg.wait_for_selector('.order-id')
    check('Đặt hàng thành công' in pg.inner_text('h1'), 'luồng mua hàng hoàn chỉnh dưới đường dẫn con')
    pg.click('a.btn-secondary'); pg.wait_for_url('**/CoffeeBeans/order-history.html'); pg.wait_for_selector('.order-card')
    check(True, 'lịch sử đơn hàng mở được')
    pg.evaluate("CB.auth.logout()")
    pg.goto('http://127.0.0.1:8766/CoffeeBeans/admin-login.html'); pg.fill('#username', 'admin'); pg.fill('#password', 'admin123'); pg.click('.login-btn'); pg.wait_for_url('**/CoffeeBeans/admin-dashboard.html')
    pg.wait_for_selector('.stat-card'); check(pg.locator('.nav-btn').count() == 8, 'admin đăng nhập và hiển thị 8 chức năng')
    pg.goto('http://127.0.0.1:8766/CoffeeBeans/admin-dashboard.html#orders'); pg.wait_for_selector('#adminMain tbody tr')
    check(pg.locator('#adminMain tbody tr').count() >= 6, 'admin thấy đơn vừa đặt từ phía khách (dữ liệu dùng chung)')
    check(bad == [], 'không có tài nguyên nội bộ nào trả mã 4xx/5xx', bad)
    check(logs == [], 'không lỗi JS/console', logs)
    b.close()
sys.exit(1 if summary() else 0)
